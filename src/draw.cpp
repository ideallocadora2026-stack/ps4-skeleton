const Uint8* glyph(char value)
{
    if (value >= 'a' && value <= 'z') value = static_cast<char>(value - 'a' + 'A');
    for (unsigned i = 0; i < sizeof(GLYPHS) / sizeof(GLYPHS[0]); ++i)
        if (GLYPHS[i].character == value) return GLYPHS[i].rows;
    return nullptr;
}
